    D_DAYNUMINWEEK       TINYINT,
    D_DAYNUMINMONTH      TINYINT,
    D_DAYNUMINYEAR       SMALLINT,
    D_MONTHNUMINYEAR     TINYINT,
    D_WEEKNUMINYEAR      TINYINT,
    D_SELLINGSEASON      VARCHAR,
    D_LASTDAYINWEEKFL    TINYINT,
    D_LASTDAYINMONTHFL   TINYINT,
    D_HOLIDAYFL          TINYINT,
    D_WEEKDAYFL          TINYINT
);


