CREATE OR REPLACE TABLE customer
(
    C_CUSTKEY       INT,
    C_NAME          VARCHAR,
    C_ADDRESS       VARCHAR,
    C_CITY          VARCHAR,
    C_NATION        VARCHAR,
    C_REGION        VARCHAR,
    C_PHONE         VARCHAR,
    C_MKTSEGMENT    VARCHAR
);

CREATE OR REPLACE TABLE lineorder
(
    LO_ORDERKEY             INT,
    LO_LINENUMBER           TINYINT,
    LO_CUSTKEY              INT,
    LO_PARTKEY              INT,
    LO_SUPPKEY              INT,
    LO_ORDERDATE            Date,
    LO_ORDERPRIORITY        VARCHAR,
    LO_SHIPPRIORITY         TINYINT,
    LO_QUANTITY             TINYINT,
    LO_EXTENDEDPRICE        INT,
    LO_ORDTOTALPRICE        INT,
    LO_DISCOUNT             TINYINT,
    LO_REVENUE              INT,
    LO_SUPPLYCOST           INT,
    LO_TAX                  TINYINT,
    LO_COMMITDATE           Date,
    LO_SHIPMODE             VARCHAR
);

CREATE OR REPLACE TABLE part
(
    P_PARTKEY       INT,
    P_NAME          VARCHAR,
    P_MFGR          VARCHAR,
    P_CATEGORY      VARCHAR,
    P_BRAND         VARCHAR,
    P_COLOR         VARCHAR,
    P_TYPE          VARCHAR,
    P_SIZE          TINYINT,
    P_CONTAINER     VARCHAR
);

CREATE OR REPLACE TABLE supplier
(
    S_SUPPKEY       INT,
    S_NAME          VARCHAR,
    S_ADDRESS       VARCHAR,
    S_CITY          VARCHAR,
    S_NATION        VARCHAR,
    S_REGION        VARCHAR,
    S_PHONE         VARCHAR
);

CREATE OR REPLACE TABLE date
(
    D_DATEKEY            Date,
    D_DATE               VARCHAR,
    D_DAYOFWEEK          VARCHAR,
    D_MONTH              VARCHAR,
    D_YEAR               SMALLINT,
